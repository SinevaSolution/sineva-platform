import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { generateTypes } from './generate_types';
import { PRODUCTION_SCHEMAS } from './index';
import { TEST_ONLY_SCHEMAS } from './test_support';

describe('generated TypeScript types', () => {
  it('the committed file is exactly what the generator produces (run `npm run generate`)', () => {
    const committed = readFileSync(join(import.meta.dirname, 'generated', 'card_types.ts'), 'utf8');
    expect(committed).toBe(generateTypes(PRODUCTION_SCHEMAS));
  });

  it('types guardrail_notice v1 with required string fields', () => {
    const out = generateTypes(PRODUCTION_SCHEMAS);
    expect(out).toContain('export interface GuardrailNoticeV1Data {');
    expect(out).toContain('specialist: string;');
    expect(out).toContain('limit_key: string;');
    expect(out).toContain('offer_key: string;');
    expect(out).toContain("'guardrail_notice': { 1: GuardrailNoticeV1Data };");
  });

  it('handles optional fields, arrays and nested objects', () => {
    const out = generateTypes(TEST_ONLY_SCHEMAS.slice(0, 1));
    expect(out).toContain('name: string;');
    expect(out).toContain('note?: string;');
    expect(out).toContain('tags?: string[];');
    expect(out).toContain('items?: Array<{');
  });

  it('marks the file as generated', () => {
    expect(generateTypes(PRODUCTION_SCHEMAS)).toMatch(/^\/\/ GENERATED by scripts\/generate_types\.ts/);
  });
});
