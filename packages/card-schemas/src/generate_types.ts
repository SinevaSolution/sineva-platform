import type { CardSchemaEntry } from './registry';

// TypeScript types from the card schema files, without a dependency. The
// schemas follow the small subset enforced by `lintSchema` (closed objects,
// capped strings and arrays, local $ref only), which keeps this generator
// short. A general-purpose generator would pull in a large dependency tree for
// a subset we control, and its output would change with its own releases.

type Schema = Record<string, unknown>;

function isSchema(value: unknown): value is Schema {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function pascal(value: string): string {
  return value
    .split('_')
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');
}

function literal(value: unknown): string {
  return typeof value === 'string' ? `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'` : JSON.stringify(value);
}

function tsType(node: Schema, root: Schema, indent: string): string {
  const ref = node['$ref'];
  if (typeof ref === 'string') {
    return `${pascal(ref.split('/').pop() ?? 'Ref')}`;
  }
  if (Array.isArray(node['enum'])) return node['enum'].map(literal).join(' | ');
  if (node['const'] !== undefined) return literal(node['const']);
  const type = node['type'];
  if (Array.isArray(type)) {
    return type.map((t) => tsType({ ...node, type: t }, root, indent)).join(' | ');
  }
  switch (type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      const items = isSchema(node['items']) ? tsType(node['items'], root, indent) : 'unknown';
      return items.includes('\n') || items.includes('|') ? `Array<${items}>` : `${items}[]`;
    }
    case 'object':
      return objectType(node, root, indent);
    default:
      return 'unknown';
  }
}

function objectType(node: Schema, root: Schema, indent: string): string {
  const properties = isSchema(node['properties']) ? node['properties'] : {};
  const required = new Set(Array.isArray(node['required']) ? (node['required'] as string[]) : []);
  const inner = `${indent}  `;
  const lines = Object.entries(properties).map(([name, child]) => {
    const optional = required.has(name) ? '' : '?';
    return `${inner}${name}${optional}: ${tsType(child as Schema, root, inner)};`;
  });
  if (lines.length === 0) return 'Record<string, never>';
  return `{\n${lines.join('\n')}\n${indent}}`;
}

export function generateTypes(schemas: CardSchemaEntry[]): string {
  const sorted = [...schemas].sort(
    (a, b) => a.card_type.localeCompare(b.card_type) || a.version - b.version,
  );
  const out: string[] = [
    '// GENERATED by scripts/generate_types.ts from schemas/{card_type}/v{n}.json. Do not edit.',
    '// Run `npm run generate` in packages/card-schemas after changing a schema.',
    '',
  ];

  for (const entry of sorted) {
    const name = `${pascal(entry.card_type)}V${entry.version}Data`;
    const body = objectType(entry.schema, entry.schema, '');
    out.push(body.startsWith('{') ? `export interface ${name} ${body}` : `export type ${name} = ${body};`);
    out.push('');
  }

  const byType = new Map<string, CardSchemaEntry[]>();
  for (const entry of sorted) {
    byType.set(entry.card_type, [...(byType.get(entry.card_type) ?? []), entry]);
  }
  out.push('/** Card data by type and version. */');
  out.push('export interface CardDataByType {');
  for (const [cardType, versions] of byType) {
    const members = versions
      .map((v) => `${v.version}: ${pascal(cardType)}V${v.version}Data`)
      .join('; ');
    out.push(`  '${cardType}': { ${members} };`);
  }
  out.push('}');
  out.push('');
  return out.join('\n');
}
