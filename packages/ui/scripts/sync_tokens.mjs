#!/usr/bin/env node
// Vendors the sineva-compro design tokens into packages/ui/src/styles and
// writes tokens.snapshot.json. Usage:
//
//   node packages/ui/scripts/sync_tokens.mjs <path-to-sineva-compro>
//
// Compro is read only. The three CSS files are copied as they are (minus the
// documented exclusion) under a header that names the compro commit, so a
// reviewer can see which compro state the platform follows. Nothing is
// hand-edited in the vendored files: platform additions live in
// app-density.css. A drift test compares the snapshot with the CSS on disk.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readCustomProperties } from './css_tokens.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const stylesDir = resolve(here, '../src/styles');

const comproArg = process.argv[2];
if (!comproArg) {
  console.error('usage: sync_tokens.mjs <path-to-sineva-compro>');
  process.exit(2);
}
const compro = resolve(comproArg);

// Marketing only: the duration of the Sino launch overlay on the public site.
// The app has no launch overlay, so the token would be dead weight.
const EXCLUDED_LINES = [/^\s*--dur-sino-launch:/];

const SECTION_START = '/* 1. Primitives and non-utility tokens */';
// Everything after this marker is compro's base layer and admin screens, not tokens.
const SECTION_END = '/*\n * 3. Shared base and the existing admin screens';

const TOKEN_SOURCES = [
  'src/app/globals.css',
  'src/styles/theme-dark.css',
  'src/styles/product-accents.css',
  'docs/design/tokens.md',
];

function read(relative) {
  return readFileSync(resolve(compro, relative), 'utf8');
}

// Reading the commit of the read-only compro checkout is the one place this
// script runs a subprocess; it never writes to that repository.
function inCompro(...args) {
  return execFileSync('git', ['-C', compro, ...args], { encoding: 'utf8' }).trim();
}

const commit = inCompro('rev-parse', 'HEAD');
const dirty = inCompro('status', '--porcelain', '--', ...TOKEN_SOURCES) !== '';

function header(source, note) {
  const state = dirty ? ' (token files had uncommitted changes in the working tree)' : '';
  return `/*
 * Vendored from sineva-compro ${source} at commit ${commit}${state}.
 * Generated by packages/ui/scripts/sync_tokens.mjs. Do not edit by hand:
 * change compro first, then run the script again. tokens.snapshot.json and
 * ui-tokens.test.ts fail when this file drifts from the snapshot.${note ? `\n * ${note}` : ''}
 */
`;
}

const globals = read('src/app/globals.css');
const start = globals.indexOf(SECTION_START);
const end = globals.indexOf(SECTION_END);
if (start < 0 || end < 0 || end < start) {
  console.error('compro globals.css no longer has the expected token section markers');
  process.exit(1);
}
const tokensBody = globals
  .slice(start, end)
  .split('\n')
  .filter((line) => !EXCLUDED_LINES.some((pattern) => pattern.test(line)))
  .join('\n')
  .trimEnd();

const files = {
  'tokens.css': `${header(
    'src/app/globals.css (sections 1 and 2)',
    'Left out on purpose: --dur-sino-launch (public-site launch overlay).',
  )}\n${tokensBody}\n`,
  'theme-dark.css': `${header('src/styles/theme-dark.css')}\n${read('src/styles/theme-dark.css')}`,
  'product-accents.css': `${header('src/styles/product-accents.css')}\n${read('src/styles/product-accents.css')}`,
};

mkdirSync(stylesDir, { recursive: true });
const snapshot = { compro_commit: commit, files: {} };
for (const [name, content] of Object.entries(files)) {
  writeFileSync(resolve(stylesDir, name), content);
  snapshot.files[name] = readCustomProperties(content);
}
writeFileSync(resolve(stylesDir, 'tokens.snapshot.json'), `${JSON.stringify(snapshot, null, 2)}\n`);
console.log(`vendored compro ${commit}${dirty ? ' (dirty token files)' : ''} into ${stylesDir}`);
